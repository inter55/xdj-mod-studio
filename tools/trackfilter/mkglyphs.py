#!/usr/bin/env python3
"""tfs_glyphs.h: lettering + icons for the TRACK FILTER screen (tfs.c),
4-bit alpha (0..15) packed two pixels per byte, rendered through aafont.py
in the deck's own Helvetica Neue faces, sized to the XDJ-1000MK2's TRACK
FILTER screen (measured from its firmware in the reference emulator).

  GT  title bar   "TRACK FILTER  USB@PLAYER1 [ 263]"   regular, cap 15
  GV  value boxes "130" "Am" "F#m"                     regular, cap 18
  GL  row labels  "BPM" "RATING" "RELATED KEY"         regular, cap 12
  GS  small caps  "MASTER" "PLAYER" "-RESET" keypad    cond. bold, cap 10
  GK  key picker  "Abm" "F#" (and its sub-labels GS)   regular, cap 14
  icons: funnel, star, star outline, tick, backspace (drawn here)
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import numpy as np
from PIL import Image, ImageDraw
import aafont as AF

UP = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
SETS = [
    ("GV", 0, 18, "0123456789ABCDEFG#bm"),
    ("GL", 0, 12, UP + "%+-"),
    ("GS", 4, 10, UP + "0123456789#bm-"),
]
# GN: title, key picker and My Tag names: all printable ASCII, cap 14, with
# room for descenders (g j p q y) -- tag names are mixed case
NAMES = "".join(chr(c) for c in range(33, 127))
GN_CAP, GN_DESC = 14, 4


def render_desc(ch, idx, cap, desc):
    """like aafont._render, but keeps `desc` rows below the baseline"""
    from PIL import ImageFont
    S = 8
    path, index = AF._font_file(AF.NEUE, idx)
    f = ImageFont.truetype(path, 40 * S // 4, index=index)
    im = Image.new("L", (f.size * 3, f.size * 3), 0)
    ImageDraw.Draw(im).text((f.size, f.size * 2), "H", font=f, fill=255, anchor="ls")
    rows = np.nonzero(np.array(im).max(axis=1) > 128)[0]
    top, base = rows[0], f.size * 2
    scale = cap / (base - top)
    bot = base + int(round(desc / scale))
    im = Image.new("L", (f.size * 3, f.size * 3), 0)
    ImageDraw.Draw(im).text((f.size, base), ch, font=f, fill=255, anchor="ls")
    a = np.array(im, float)[top:bot]
    xs = np.nonzero(a.max(axis=0) > 20)[0]
    if len(xs) == 0:
        return np.zeros((cap + desc, 3))
    a = a[:, xs[0]:xs[-1] + 1]
    w = max(1, round(a.shape[1] * scale))
    out = Image.fromarray(a.astype(np.uint8)).resize((w, cap + desc), Image.LANCZOS)
    return np.clip(np.array(out, float) / 255.0, 0, 1)


def pack(a):
    """alpha 0..1 (H x W) -> 4-bit nibbles, row-major, W padded to even"""
    q = np.clip(np.round(a * 15), 0, 15).astype(np.uint8)
    if q.shape[1] & 1:
        q = np.hstack([q, np.zeros((q.shape[0], 1), np.uint8)])
    return (q[:, 0::2] | (q[:, 1::2] << 4)).ravel()


def shape(w, h, draw):
    S = 8
    im = Image.new("L", (w * S, h * S), 0)
    draw(ImageDraw.Draw(im), S)
    return np.array(im.resize((w, h), Image.LANCZOS), float) / 255.0


def star(fill):
    import math
    def d(dr, S):
        cx, cy, R, r = 11 * S, 11.5 * S, 11 * S, 4.4 * S
        pts = [(cx + (R if k % 2 == 0 else r) * math.sin(k * math.pi / 5),
                cy - (R if k % 2 == 0 else r) * math.cos(k * math.pi / 5)) for k in range(10)]
        if fill:
            dr.polygon(pts, fill=255)
        else:
            dr.line(pts + [pts[0]], fill=255, width=int(1.3 * S))
    return shape(22, 22, d)


ICONS = {
    "funnel": shape(20, 20, lambda d, S: d.polygon(
        [(0, 2 * S), (20 * S, 2 * S), (12 * S, 11 * S), (12 * S, 18 * S),
         (8 * S, 16 * S), (8 * S, 11 * S)], fill=255)),
    "star1": star(True),
    "star0": star(False),
    "tick": shape(18, 16, lambda d, S: d.line(
        [(2 * S, 8 * S), (7 * S, 13 * S), (16 * S, 2 * S)], fill=255, width=int(2.4 * S))),
    "bksp": shape(30, 18, lambda d, S: (
        d.polygon([(0, 9 * S), (9 * S, 0), (30 * S, 0), (30 * S, 18 * S), (9 * S, 18 * S)], fill=255),
        d.line([(14 * S, 4 * S), (24 * S, 14 * S)], fill=0, width=int(2.4 * S)),
        d.line([(24 * S, 4 * S), (14 * S, 14 * S)], fill=0, width=int(2.4 * S)))),
    "le": shape(14, 14, lambda d, S: (            # "less or equal", two bars under
        d.line([(13 * S, 0), (1 * S, 4 * S), (13 * S, 8 * S)], fill=255, width=int(1.6 * S)),
        d.line([(1 * S, 10 * S), (13 * S, 6 * S)], fill=255, width=int(1.6 * S)),
        d.line([(1 * S, 13 * S), (13 * S, 9 * S)], fill=255, width=int(1.6 * S)))),
    "pm": shape(13, 14, lambda d, S: (
        d.line([(6.5 * S, 0), (6.5 * S, 10 * S)], fill=255, width=int(1.6 * S)),
        d.line([(0, 5 * S), (13 * S, 5 * S)], fill=255, width=int(1.6 * S)),
        d.line([(0, 13 * S), (13 * S, 13 * S)], fill=255, width=int(1.6 * S)))),
}

out = ["/* generated by mkglyphs.py -- do not edit */\n"]
for pre, idx, H, chars in SETS:
    gl = [AF._render(c, AF.NEUE, idx, H) for c in chars]
    offs, data = [], bytearray()
    for g in gl:
        offs.append(len(data))
        data += bytes(pack(g))
    out += [f"#define {pre}_H {H}\n#define {pre}_N {len(chars)}\n",
            f"static const char {pre}_chars[] = \"{chars}\";\n",
            f"static const unsigned char {pre}_w[] = {{" + ",".join(str(g.shape[1]) for g in gl) + "};\n",
            f"static const unsigned short {pre}_o[] = {{" + ",".join(map(str, offs)) + "};\n",
            f"static const unsigned char {pre}_a[] = {{" + ",".join(map(str, data)) + "};\n"]
gl = [render_desc(c, 0, GN_CAP, GN_DESC) for c in NAMES]
offs, data = [], bytearray()
for g in gl:
    offs.append(len(data))
    data += bytes(pack(g))
out += [f"#define GN_H {GN_CAP + GN_DESC}\n#define GN_CAP {GN_CAP}\n#define GN_N {len(NAMES)}\n",
        "static const char GN_chars[] = " + '"' + NAMES.replace("\\", "\\\\").replace('"', '\\"') + '";\n',
        "static const unsigned char GN_w[] = {" + ",".join(str(g.shape[1]) for g in gl) + "};\n",
        "static const unsigned short GN_o[] = {" + ",".join(map(str, offs)) + "};\n",
        "static const unsigned char GN_a[] = {" + ",".join(map(str, data)) + "};\n"]
for name, a in ICONS.items():
    out += [f"#define IC_{name.upper()}_W {a.shape[1]}\n#define IC_{name.upper()}_H {a.shape[0]}\n",
            f"static const unsigned char IC_{name}[] = {{" + ",".join(map(str, pack(a))) + "};\n"]
open(os.path.join(HERE, "tfs_glyphs.h"), "w").write("".join(out))
print("tfs_glyphs.h written:", sum(len(x) for x in out) // 1024, "KB of source")
